static const uint8_t EEPROM_MAGIC_VALUE = 0x5A;

void initDefaultEEPROMIfNeeded() {
    uint8_t magic = EEPROM.read(EEPROM_GAIN);

    if (magic == EEPROM_MAGIC_VALUE) {
        Serial.println("EEPROM already initialized");
        return;
    }

    Serial.println("EEPROM empty, writing default values");

    EEPROM.write(EEPROM_GAIN, EEPROM_MAGIC_VALUE);

    EEPROM.write(EEPROM_MODE, 1);
    EEPROM.write(EEPROM_COLOR, 90);
    EEPROM.write(EEPROM_COLOR_H, 90);
    EEPROM.write(EEPROM_COLOR_M, 90);
    EEPROM.write(EEPROM_COLOR_S, 90);
    EEPROM.write(EEPROM_COLOR_W, 90);
    EEPROM.write(EEPROM_BRIGHTNESS, 30);

    EEPROM.write(EEPROM_START_H, 0);
    EEPROM.write(EEPROM_START_M, 0);
    EEPROM.write(EEPROM_END_H, 23);
    EEPROM.write(EEPROM_END_M, 59);

    EEPROM.write(EEPROM_GIF_COUNT, 3);
    EEPROM.write(EEPROM_GIF_NO, 10);
    EEPROM.write(EEPROM_GIF_DELAY, 50);
    EEPROM.write(EEPROM_RANDOM_MIN, 30);
    EEPROM.write(EEPROM_RGB_ORDER, 0); // 預設 RGB

    uint16_t defaultThemeA = 0xF800;
    uint16_t defaultThemeB = 0x0000;
    EEPROM.put(EEPROM_THEME_A, defaultThemeA);
    EEPROM.put(EEPROM_THEME_B, defaultThemeB);

    EEPROM.write(EEPROM_CUSTOM_ENABLE, 0);

    for (int i = 0; i < 24; i++) {
        EEPROM.write(EEPROM_CUSTOM_TABLE + i, 99);
    }

    dataType wifiData;
    memset(&wifiData, 0, sizeof(wifiData));
    EEPROM.put(EEPROM_WIFI_ADDR, wifiData);

    EEPROM.commit();

    Serial.println("Default EEPROM written");
}







